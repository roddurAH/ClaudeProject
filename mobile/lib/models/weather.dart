import 'localized.dart';

class Forecast {
  Forecast({required this.daily, required this.advisories, this.temperature, this.humidity, this.code, this.wind, this.source, this.stale = false, this.districtBn, this.districtEn});

  final double? temperature;
  final int? humidity;
  final int? code;
  final double? wind;
  final List<DailyForecast> daily;
  final List<Advisory> advisories;
  final String? source;
  final bool stale;
  final String? districtBn, districtEn;

  String district(String lang) => pick(districtBn, districtEn, lang);

  factory Forecast.fromJson(Map<String, dynamic> j) {
    final current = (j['current'] as Map?) ?? {};
    final district = (j['district'] as Map?) ?? {};
    return Forecast(
      temperature: toDoubleOrNull(current['temperature']),
      humidity: toIntOrNull(current['humidity']),
      code: toIntOrNull(current['code']),
      wind: toDoubleOrNull(current['wind']),
      daily: (j['daily'] as List? ?? []).map((e) => DailyForecast.fromJson(e as Map<String, dynamic>)).toList(),
      advisories: (j['advisories'] as List? ?? []).map((e) => Advisory.fromJson(e as Map<String, dynamic>)).toList(),
      source: j['source']?.toString(),
      stale: j['stale'] == true,
      districtBn: district['name_bn']?.toString(),
      districtEn: district['name_en']?.toString(),
    );
  }
}

class DailyForecast {
  DailyForecast({required this.date, this.code, this.tMax, this.tMin, this.rainMm, this.rainProbability, this.windMax});

  final DateTime date;
  final int? code;
  final double? tMax, tMin, rainMm, windMax;
  final int? rainProbability;

  factory DailyForecast.fromJson(Map<String, dynamic> j) => DailyForecast(
        date: DateTime.tryParse(j['date']?.toString() ?? '') ?? DateTime.now(),
        code: toIntOrNull(j['code']),
        tMax: toDoubleOrNull(j['t_max']),
        tMin: toDoubleOrNull(j['t_min']),
        rainMm: toDoubleOrNull(j['rain_mm']),
        rainProbability: toIntOrNull(j['rain_probability']),
        windMax: toDoubleOrNull(j['wind_max']),
      );
}

/// Rule-based farm advice generated by the server from the forecast.
class Advisory {
  Advisory({required this.key, required this.level, required this.icon, required this.titleBn, required this.titleEn, required this.bodyBn, required this.bodyEn});

  final String key, level, icon, titleBn, titleEn, bodyBn, bodyEn;

  String title(String lang) => pick(titleBn, titleEn, lang);
  String body(String lang) => pick(bodyBn, bodyEn, lang);

  String get emoji => switch (icon) {
        'rain' => '🌧️',
        'umbrella' => '☔',
        'storm' => '🌪️',
        'heat' => '🔥',
        'cold' => '🥶',
        'disease' => '🦠',
        'water' => '💧',
        'spray' => '✅',
        _ => '🌾',
      };

  factory Advisory.fromJson(Map<String, dynamic> j) => Advisory(
        key: j['key']?.toString() ?? '',
        level: j['level']?.toString() ?? 'info',
        icon: j['icon']?.toString() ?? '',
        titleBn: j['title_bn']?.toString() ?? '',
        titleEn: j['title_en']?.toString() ?? '',
        bodyBn: j['body_bn']?.toString() ?? '',
        bodyEn: j['body_en']?.toString() ?? '',
      );
}

/// Broadcast alert from the admin panel (flood, cyclone, pest outbreak …).
class FarmAlert {
  FarmAlert({required this.id, required this.severity, required this.titleBn, required this.titleEn, required this.bodyBn, required this.bodyEn});

  final int id;
  final String severity, titleBn, titleEn, bodyBn, bodyEn;

  String title(String lang) => pick(titleBn, titleEn, lang);
  String body(String lang) => pick(bodyBn, bodyEn, lang);

  factory FarmAlert.fromJson(Map<String, dynamic> j) => FarmAlert(
        id: toIntOrNull(j['id']) ?? 0,
        severity: j['severity']?.toString() ?? 'info',
        titleBn: j['title_bn']?.toString() ?? '',
        titleEn: j['title_en']?.toString() ?? '',
        bodyBn: j['body_bn']?.toString() ?? '',
        bodyEn: j['body_en']?.toString() ?? '',
      );
}
